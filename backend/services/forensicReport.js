import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

export async function generateForensicReport(data) {
    const pdfDoc = await PDFDocument.create();
    const page = pdfDoc.addPage([595.28, 841.89]); // A4
    const { width, height } = page.getSize();

    const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
    const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

    let logoRightEdge = 40;

    // ProvenanceVault Logo - No background to avoid blending
    try {
        const logoPath = path.resolve(__dirname, '../../frontend/src/assets/logowithname.png');
        if (fs.existsSync(logoPath)) {
            const logoBytes = fs.readFileSync(logoPath);
            const logoImage = await pdfDoc.embedPng(logoBytes);
            // Scale to fit height nicely
            const maxLogoHeight = 55;
            const scaleFactor = maxLogoHeight / logoImage.height;
            const scaledWidth = logoImage.width * scaleFactor;
            
            page.drawImage(logoImage, {
                x: 40,
                y: height - 80,
                width: scaledWidth,
                height: maxLogoHeight,
            });
            logoRightEdge = 40 + scaledWidth + 20; // adding 20px padding
        }
    } catch (e) {
        console.error("Could not load ProvenanceVault logo", e);
    }

    // Ensure text starts after the logo
    const textStartX = Math.max(logoRightEdge, 220);

    // WESEE / SIH Header Text
    page.drawText('WESEE (Weapon and Electronics Systems Engineering)', {
        x: textStartX,
        y: height - 40,
        size: 11,
        font: fontBold,
        color: rgb(0.1, 0.1, 0.1),
    });
    
    page.drawText('MINISTRY OF DEFENCE, GOVERNMENT OF INDIA', {
        x: textStartX,
        y: height - 55,
        size: 10,
        font: font,
        color: rgb(0.4, 0.4, 0.4),
    });

    page.drawText('OFFICIAL FORENSIC ATTRIBUTION REPORT', {
        x: textStartX,
        y: height - 75,
        size: 13,
        font: fontBold,
        color: rgb(0.7, 0.1, 0.1), // Dark red for official look
    });

    // Separator Line
    page.drawLine({
        start: { x: 40, y: height - 100 },
        end: { x: width - 40, y: height - 100 },
        thickness: 2,
        color: rgb(0.2, 0.2, 0.2),
    });

    let currentY = height - 130;

    // Intro paragraph
    page.drawText('This document is a highly classified cryptographic analysis report generated by the', { x: 50, y: currentY, size: 10, font });
    currentY -= 15;
    page.drawText('ProvenanceVault system. It establishes mathematical proof of document leakage.', { x: 50, y: currentY, size: 10, font });
    currentY -= 30;

    const drawLine = (y) => {
        page.drawLine({
            start: { x: 50, y },
            end: { x: width - 50, y },
            thickness: 1,
            color: rgb(0.8, 0.8, 0.8),
        });
    };

    const drawSectionHeader = (title, y) => {
        page.drawRectangle({
            x: 50, y: y - 6, width: width - 100, height: 20, color: rgb(0.92, 0.95, 1)
        });
        page.drawText(title, { x: 55, y, size: 11, font: fontBold, color: rgb(0.04, 0.15, 0.35) });
    };

    const drawField = (label, value, y, isHash = false) => {
        page.drawText(label + ':', { x: 55, y, size: 10, font: fontBold, color: rgb(0.2, 0.2, 0.2) });
        const valStr = String(value);
        if (isHash && valStr.length > 50) {
            page.drawText(valStr.slice(0, 50), { x: 200, y: y + 4, size: 8, font: font });
            page.drawText(valStr.slice(50), { x: 200, y: y - 6, size: 8, font: font });
        } else {
            page.drawText(valStr, { x: 200, y, size: 10, font: font });
        }
    };

    drawSectionHeader('1. INCIDENT DETAILS', currentY);
    currentY -= 25;
    drawField('Case Reference', `CASE-${crypto.randomUUID().toUpperCase()}`, currentY);
    currentY -= 20;
    drawField('Report Date', new Date().toUTCString(), currentY);
    currentY -= 35;

    drawSectionHeader('2. DOCUMENT INTELLIGENCE', currentY);
    currentY -= 25;
    drawField('Source Document', data.document.filename, currentY);
    currentY -= 20;
    drawField('Document Hash', data.document.originalHash, currentY, true);
    currentY -= 25;
    drawField('Watermark ID', data.watermarkId, currentY, true);
    currentY -= 35;

    drawSectionHeader('3. SUSPECT ATTRIBUTION', currentY);
    currentY -= 25;
    drawField('Attributed Recipient', `${data.recipient.name}`, currentY);
    currentY -= 20;
    drawField('Ethereum Address', data.recipient.eth_address, currentY, true);
    currentY -= 25;
    drawField('Decryption Time', new Date(Number(data.decryptionEvent.timestamp)).toISOString(), currentY);
    currentY -= 20;
    const keyStatusText = data.keyStatus === 'valid-at-time-of-decryption' 
        ? 'Valid at Decryption Time' 
        : (data.keyStatus === 'revoked-before-decryption' ? 'Revoked Before Decryption' : 'Unknown');
    drawField('Key Status at Access', keyStatusText, currentY);
    currentY -= 35;

    drawSectionHeader('4. CRYPTOGRAPHIC PROOF', currentY);
    currentY -= 25;
    drawField('Blockchain TX Hash', data.decryptionEvent.txHash || 'Pending / Unknown', currentY, true);
    currentY -= 25;
    drawField('ML-DSA Signature', data.signatureVerified ? 'VERIFIED - Mathematically Bound to Suspect' : 'FAILED / COMPROMISED', currentY);
    currentY -= 35;

    drawLine(140);

    // Ashoka Stamp
    try {
        const stampPath = path.resolve(__dirname, '../../frontend/src/assets/AshokaStamp.png');
        if (fs.existsSync(stampPath)) {
            const stampBytes = fs.readFileSync(stampPath);
            const stampImage = await pdfDoc.embedPng(stampBytes);
            const scaleFactor = 80 / stampImage.height;
            page.drawImage(stampImage, {
                x: width - (stampImage.width * scaleFactor) - 50,
                y: 150,
                width: stampImage.width * scaleFactor,
                height: 80,
            });
        }
    } catch(e) {
        console.error("Could not load Ashoka stamp", e);
    }

    // Footer
    const footerText = "CONFIDENTIAL & PROPRIETARY. This report is generated under the authority of WESEE (Ministry of Defence). " +
                       "Digital signatures are verified against the localized post-quantum blockchain ledger.";
                       
    page.drawText(footerText, {
        x: 50,
        y: 80,
        size: 8,
        font,
        color: rgb(0.4, 0.4, 0.4),
        maxWidth: width - 100,
    });
    
    page.drawText("Smart India Hackathon 2024 - Project SIH26237", {
        x: 50,
        y: 60,
        size: 8,
        font: fontBold,
        color: rgb(0.2, 0.2, 0.2),
    });

    const pdfBytes = await pdfDoc.save();
    return pdfBytes;
}
